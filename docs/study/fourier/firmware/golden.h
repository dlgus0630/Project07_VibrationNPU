// ============================================================================
//
// 이 파일이 하는 일 한 줄 요약: golden.c가 계산하는 결과를 담는 "그릇"의
// 모양(구조체)과, golden.c의 유일한 공개 함수 하나를 선언합니다.
//
// "Golden model"이 뭔가?
// -----------------------------------------------------------------------
// 하드웨어(FPGA)와 소프트웨어(ARM) 양쪽에서 "같은 계산"을 하는 코드를
// 각각 따로 만들면, 둘 중 하나가 틀렸을 때 서로 비교해서 잡아낼 수
// 있습니다. 이때 "정답이라고 믿고 기준으로 삼는 쪽"을 golden model(황금
// 기준 모델)이라고 부릅니다. 이 프로젝트에서는 fft64_features.v +
// npu_2pe.v(하드웨어)가 계산하는 것과 **완전히 같은 수학**을 golden.c가
// 순수 C로 다시 구현해서, 두 결과가 100% 일치(bit-exact)하는지 매번
// 확인합니다(main.c의 `run_window()`에서 `match` 변수로 비교). 이렇게
// "같은 계산을 독립적으로 두 번 구현해서 비교"하는 건 안전이 중요한
// 임베디드 시스템에서 흔히 쓰는 검증 기법입니다.
//
// 왜 golden.c는 PC에서도, ARM에서도 똑같이 돌아가는가?
// -----------------------------------------------------------------------
// golden.c는 표준 C(stdint.h만 사용)로만 작성되어 있어서 특정 하드웨어에
// 의존하지 않습니다. 그래서 PC용 host_check.c(자동 테스트)와 ARM용
// main.c(실시간 실물 비교) 양쪽에서 재컴파일만 하면 그대로 재사용됩니다
// — "같은 소스 코드 = 같은 결과"라는 것을 보장하는 가장 간단한 방법입니다.
// ============================================================================

#ifndef GOLDEN_H
#define GOLDEN_H
#include <stdint.h>

// 한 번의 추론(64개 진동 샘플 -> 정상/이상 판정) 결과를 전부 담는 구조체.
// FFT 중간 결과(re/im)까지 남겨두는 이유는, 디버깅하거나 하드웨어와
// 정확히 어느 단계에서 값이 어긋났는지 비교할 때 유용하기 때문입니다.
typedef struct {
    int16_t re[64],im[64];      // FFT 결과(실수부/허수부), fft64_features.v의 re/im과 대응
    uint8_t features[4],hidden[4]; // FFT 4개 대역 특징, 신경망 은닉층 4개 출력
    int8_t logits[2];            // 최종 두 점수(정상/이상)
    uint8_t class_id;            // 0=정상, 1=이상
} inference_result;

// 이 헤더가 외부에 공개하는 유일한 함수: 64개 샘플을 넣으면 결과 구조체를 채워준다.
void infer_integer(const int16_t samples[64],inference_result *result);
#endif
