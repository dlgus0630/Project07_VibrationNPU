// [공부용 주석 사본] fourier/firmware/host_check.c
// 실제 커밋되는 원본에는 이런 상세 주석이 없습니다. 이 파일은 학습 전용입니다.
// ============================================================================
//
// 이 파일이 하는 일 한 줄 요약: "PC(호스트 컴퓨터)에서 golden.c(하드웨어와
// 똑같은 계산을 하는 순수 C 코드)를 자동으로 20개 테스트 벡터에 대해 돌려보고,
// 미리 만들어둔 '정답 파일(.mem)'과 한 값도 빠짐없이 비교하는 자동 검증
// 프로그램"입니다. golden.c의 계산 로직 자체는 docs/study/fourier/firmware/
// golden.c 사본을 먼저 보고 오면 이해가 훨씬 쉽습니다 — 이 파일은 그
// golden.c를 "테스트하는" 쪽입니다.
//
// 왜 이 검증 단계가 필요한가 (검증 체인에서의 위치)
// -----------------------------------------------------------------------
// 이 프로젝트는 같은 계산(FFT + 작은 신경망)을 세 곳에서 각각 독립적으로
// 구현합니다: ① Verilog RTL(fft64_features.v, npu_2pe.v — 실제 FPGA에서
// 도는 것), ② golden.c(순수 C, ARM에서도 PC에서도 컴파일되는 이식성 있는
// 참조 구현). 이 host_check.c는 그중 golden.c를 "FPGA를 켜지 않고도, 그냥
// 노트북에서 컴파일 한 번으로" 빠르게 검증하기 위한 것입니다. 만약
// golden.c 자체에 버그가 있다면, 나중에 ARM에서 이 golden.c와 실제 RTL
// 결과를 비교할 때 "둘 다 똑같이 틀렸는데 우연히 일치해서" 버그를 놓칠
// 수도 있습니다. 그래서 golden.c를 미리 별도의 정답(아마도 파이썬 등
// 다른 도구로 생성된 .mem 파일들)과 먼저 맞춰보는, "검증 도구 자체를
// 검증하는" 단계가 필요합니다.
//
// `.mem` 파일 포맷이 Verilog와 C 양쪽에서 "재사용"된다는 것
// -----------------------------------------------------------------------
// `.mem` 파일은 원래 Verilog의 `$readmemh("파일.mem", 메모리배열)` 시스템
// 태스크가 읽으려고 만들어진 포맷입니다 — 줄마다(또는 공백으로 구분해서)
// 16진수 숫자가 하나씩 쓰여 있는 아주 단순한 텍스트 파일입니다(예:
// `003f\nffc2\n...`). 이 프로젝트는 신경망 가중치나 테스트 벡터, 기대
// 출력값 등을 전부 이 `.mem` 포맷으로 만들어두고, Verilog 시뮬레이션에서는
// `$readmemh`로, 이 C 코드에서는 `fscanf(f,"%x",&v)`로 "같은 파일을 두
// 언어에서 똑같이 읽어들입니다". `%x`는 "16진수로 읽어라"는 뜻으로,
// `$readmemh`의 "hex memory"와 정확히 대응되는 포맷 해석 방식입니다. 이렇게
// 파일 포맷을 하나로 통일해두면, "Verilog 테스트벤치용 정답 파일 따로,
// C 테스트용 정답 파일 따로" 두 벌을 만들 필요 없이 같은 파일 하나로 두
// 검증 경로 모두를 돌릴 수 있어서 정답 데이터가 서로 어긋날 위험이 줄어듭니다.
//
// `value()` 함수: 부호 없는 16진수를 "부호 있는" 값으로 되돌리기
// -----------------------------------------------------------------------
// `.mem` 파일에는 그냥 16진수 비트 패턴만 적혀 있어서(예: 8비트라면
// `ff`), 이걸 "부호 있는 값(signed)"으로 해석해야 하는지 "부호 없는 값
// (unsigned)"으로 해석해야 하는지는 파일 자체에는 안 적혀 있습니다. 그래서
// `value(f,bits,sign)`처럼 "몇 비트짜리인지"와 "부호가 있는지"를 호출하는
// 쪽에서 알려줘야 합니다. `sign && (v&(1U<<(bits-1)))`는 "부호를 따져야
// 하고, 그 값의 최상위 비트(부호 비트)가 1이면"이라는 뜻이고, 그 경우
// `(int)v-(1<<bits)`로 2의 보수 표현을 실제 음수값으로 변환합니다(예:
// 8비트 `ff` → 부호 없이 읽으면 255, 부호 있게 읽으면 -1). 이건
// golden.c에서 다뤘던 "하드웨어와 C가 정수 연산 규칙을 똑같이 맞춰야
// 한다"는 주제의 연장선입니다 — 값 하나를 파일에서 읽어들이는 단계부터
// 이미 "이게 부호 있는 값인지 아닌지"를 정확히 알고 있어야 나중에
// 비교가 의미 있어집니다.
//
// `goto fail` 패턴: C에서 "에러 시 즉시 정리하고 빠져나가기"
// -----------------------------------------------------------------------
// C++이나 Python과 달리 C에는 예외(exception)가 없습니다. 그래서 "루프
// 안 깊숙한 곳에서 문제를 발견하면 즉시 멈추고 나가고 싶다"는 요구를
// 표현할 마땅한 문법이 적습니다. `break`는 가장 안쪽 루프 하나만 빠져나가고,
// 이 코드처럼 `for(test...)` 바깥 루프 안에 `for(n...)` 안쪽 루프가 여러
// 겹으로 중첩돼 있으면 `break`로는 바깥 루프까지 한 번에 못 빠져나갑니다.
// 이럴 때 C에서 흔히 쓰는 관용구가 "실패하면 `goto fail;`로 함수 맨 아래
// 정리 구역으로 점프한다"는 패턴입니다. 이 코드의 `fail:` 레이블은 바로
// 그 정리 구역으로, 실패 원인(`test`, `n` 번호)을 stderr에 출력하고
// 1(실패)을 반환합니다. 주의할 점: goto가 무분별하게 쓰이면 코드 흐름을
// 추적하기 어려워져서 악명이 높지만(‘goto는 해롭다’는 유명한 격언도
// 있습니다), "에러 처리 후 정리하고 함수를 빠져나가는" 이 특정 용도만큼은
// 리눅스 커널을 비롯한 많은 C 프로젝트에서 여전히 표준적으로 쓰이는
// 관용구입니다 — 오히려 억지로 플래그 변수를 여러 겹 두는 것보다 더
// 읽기 쉬운 경우가 많습니다.
//
// 전체 흐름 정리
// -----------------------------------------------------------------------
// 7개의 `.mem` 파일(samples, fft_re, fft_im, features, hidden, logits,
// class)을 동시에 열어두고, 테스트 벡터 20개(윈도우 20개)를 순서대로
// 돌립니다. 각 윈도우마다: ① samples.mem에서 64개 입력 샘플을 읽고,
// ② golden.c의 `infer_integer()`를 호출해서 결과를 계산하고, ③ 계산된
// FFT 실수부/허수부 64개씩, 특징 4개, 은닉값 4개, logit 2개, class_id
// 1개, 총 137개 값을 각각 대응하는 `.mem` 파일에서 하나씩 읽어와 정확히
// 일치하는지 비교합니다. 20개 윈도우 전부 통과하면 "HOND C PASS: 20
// windows, 2560 FFT components, 220 result values"를 출력합니다(2560 =
// 20*64*2, 220 = 20*(4+4+2+1)). 이 숫자 자체도 "정말 몇 개의 값을
// 비교했는지"를 사람이 눈으로 확인할 수 있게 해주는 작은 배려입니다.
// ============================================================================

#include <stdio.h>
#include <stdlib.h>
#include "golden.h"
// open_mem: "data/이름.mem" 경로를 만들어서 그 파일을 읽기 모드로 연다.
// 실패하면(파일이 없거나 권한 문제 등) perror로 이유를 출력하고 즉시 종료(exit(2)).
static FILE *open_mem(const char *name) {
    char path[256];FILE *f;
    if(snprintf(path,sizeof path,"data/%s.mem",name)<0)exit(2);
    // ↑ snprintf가 음수를 반환하는 것은 출력 에러(아주 드묾) — 방어적 체크.
    f=fopen(path,"r");if(!f){perror(path);exit(2);}return f;
}
// value: .mem 파일에서 16진수 하나를 읽어서, 필요하면 부호 있는 값으로 변환해 돌려준다.
// bits: 이 값이 원래 몇 비트짜리인지(부호 판단에 필요). sign: 부호 있는 값으로 해석할지.
static int value(FILE *f,int bits,int sign) {
    unsigned v;if(fscanf(f,"%x",&v)!=1){fputs("truncated vector\n",stderr);exit(2);}
    // ↑ fscanf가 정확히 1개의 값을 못 읽으면(파일이 예상보다 일찍 끝났다는 뜻)
    //   "truncated vector"(벡터가 중간에 잘렸다) 메시지를 내고 종료.
    return sign && (v&(1U<<(bits-1)))?(int)v-(1<<bits):(int)v;
    // ↑ 부호 있는 해석이 필요하고 최상위 비트(부호 비트)가 1이면 2의 보수 변환,
    //   아니면 그냥 부호 없는 값 그대로 반환.
}
int main(void) {
    // 7개의 .mem 파일을 동시에 오픈 — 매 윈도우마다 이 7개 스트림에서
    // 순서대로 값을 하나씩 계속 읽어나가는 구조(파일 포인터가 각자 진행됨).
    FILE *x=open_mem("samples"),*re=open_mem("fft_re"),*im=open_mem("fft_im");
    FILE *f=open_mem("features"),*h=open_mem("hidden"),*o=open_mem("logits"),*c=open_mem("class");
    int test,n;int16_t samples[64];inference_result r;
    for(test=0;test<20;test++) {
        // ↑ 테스트 벡터(윈도우) 20개를 순서대로 처리
        for(n=0;n<64;n++)samples[n]=(int16_t)value(x,16,1);
        // ↑ samples.mem에서 이번 윈도우의 입력 샘플 64개를 읽어옴(16비트, 부호 있음)
        infer_integer(samples,&r);
        // ↑ golden.c의 핵심 함수 호출 — 하드웨어(FFT+NPU)와 동일한 계산을 여기서 재현
        for(n=0;n<64;n++)if(r.re[n]!=value(re,16,1)||r.im[n]!=value(im,16,1))goto fail;
        // ↑ FFT 결과(실수부/허수부 각 64개)를 정답 파일과 하나씩 비교. 하나라도
        //   다르면 즉시 goto fail로 점프(더 볼 것도 없이 이 테스트는 실패).
        for(n=0;n<4;n++)if(r.features[n]!=value(f,8,0)||r.hidden[n]!=value(h,8,0))goto fail;
        // ↑ 주파수 대역 특징 4개, 은닉층 출력 4개 비교(둘 다 부호 없는 8비트 0~127 범위)
        for(n=0;n<2;n++)if(r.logits[n]!=value(o,8,1))goto fail;
        // ↑ 최종 출력층 logit 2개 비교(부호 있는 8비트, ReLU 없어서 음수 가능)
        if(r.class_id!=value(c,8,0))goto fail;
        // ↑ 마지막으로 최종 판정(0=정상, 1=이상) 1개 비교
    }
    fclose(x);fclose(re);fclose(im);fclose(f);fclose(h);fclose(o);fclose(c);
    // ↑ 20개 윈도우 전부 통과했을 때만 여기 도달 — 열었던 파일 7개 모두 정리
    puts("HOST C PASS: 20 windows, 2560 FFT components, 220 result values");return 0;
    // ↑ 2560 = 20 * 64 * 2(re+im), 220 = 20 * (4+4+2+1) — 실제로 비교한 값 개수를
    //   사람이 검증 커버리지를 눈으로 확인할 수 있게 명시적으로 출력
fail:fprintf(stderr,"HOST C FAIL case %d element %d\n",test,n);return 1;
    // ↑ goto로 여기 도달하면, 어느 테스트(test)의 몇 번째 값(n)에서 틀렸는지
    //   알려주고 실패(1)로 종료 — "에러 시 즉시 정리하고 빠져나가기" 패턴의
    //   정리 구역(clean-up section)이 바로 이 fail: 레이블 아래 코드.
}
