// 이 모듈이 하는 일 한 줄 요약: "몇 % 동안 켤지(duty)를 받아서 실제 PWM 파형을
// 만들어내는 회로"
//
// PWM(Pulse Width Modulation)이 뭔가?
// -----------------------------------------------------------------------
// 모터에 "평균적으로 50%만큼의 전압"을 주고 싶을 때, FPGA는 아날로그 전압을
// 직접 만들 수 없으니 대신 "디지털 핀을 아주 빠르게 켰다 껐다"를 반복해서
// 평균 효과를 냅니다. 한 주기(PERIOD 클럭) 중에서 앞쪽 duty%만큼은 1(켜짐),
// 나머지는 0(꺼짐)으로 만드는 게 PWM입니다. L298N 같은 모터 드라이버는 이
// PWM 신호의 평균 전압을 그대로 모터에 전달합니다.
//
// 카운터 기반 PWM의 기본 구조
// -----------------------------------------------------------------------
// `count`가 0부터 PERIOD-1까지 매 클럭 1씩 증가하다가 다시 0으로 돌아가는
// "톱니파 카운터"입니다. `pwm = (count < threshold)`로, count가 threshold보다
// 작은 동안만 1을 출력합니다. threshold가 PERIOD의 몇 %냐에 따라 duty가
// 정해집니다. 예를 들어 PERIOD=5000, threshold=2500이면 정확히 50% duty가
// 됩니다.
//
// duty를 threshold로 바꾸는 계산
// -----------------------------------------------------------------------
// 이 프로젝트에서 duty는 13비트 정수로 표현되는데, 4096이 "100%"를 의미하는
// 컨벤션을 씁니다(즉 12비트 고정소수점, Q12 스타일). 그래서
//   threshold = duty * PERIOD / 4096
// 를 계산해야 합니다. `(64'd1*limited*PERIOD)>>12`가 바로 이 공식입니다
// (나누기 4096은 "오른쪽으로 12비트 시프트"와 같습니다. 4096 = 2^12이기
// 때문입니다). 64비트로 확장해서 곱하는 이유는 duty(13비트) × PERIOD(수천~수만)
// 곱이 32비트를 넘을 수도 있어서 중간 계산에서 값이 잘리지 않게 하기 위함입니다.
//
// `limited`가 왜 필요한가?
// -----------------------------------------------------------------------
// duty가 혹시라도 4096(100%)을 넘는 값으로 들어오면(예: 상위 로직의 버그나
// 오버슈트), threshold 계산이 PERIOD보다 커져서 이상 동작할 수 있습니다.
// 그래서 4096을 넘으면 4096으로 강제로 잘라줍니다 — "방어적 클램프"입니다.
//
// 왜 duty를 "주기 경계에서만" 갱신하는가?
// -----------------------------------------------------------------------
// `else if(count==PERIOD-1)begin count<=0;threshold<=scaled...;end`를 보면,
// 새로운 duty 값(threshold)은 카운터가 한 바퀴를 다 돈 순간에만 반영됩니다.
// 만약 주기 도중에 threshold가 갑자기 바뀌면, 이번 주기의 파형이 찌그러질
// 수 있습니다(예: count가 이미 threshold를 넘어 0으로 내려가 있었는데
// threshold가 커지면 순간적으로 다시 1로 튀는 등). "매 주기가 시작할 때만
// duty를 갱신"하면 파형이 항상 깨끗한 사각파 형태를 유지합니다. 이건 실제
// PWM IC들도 흔히 쓰는 방식입니다.
//
// enable이 왜 있는가?
// -----------------------------------------------------------------------
// `enable=0`이면 그냥 duty를 0인 것처럼 처리하는 게 아니라, 아예 카운터
// 자체를 0으로 묶어두고(`count<=0;threshold<=0;`) PWM 핀을 즉시 0으로
// 내립니다(`assign pwm=enable && !rst && ...`에서 enable이 곱해져 있으므로).
// "즉시 끊는다"가 중요한 이유는, 안전 정지(latch) 상황에서 "다음 주기
// 경계까지 기다렸다가 끄기"는 너무 느릴 수 있기 때문입니다 — 안전 관련
// 신호는 주저 없이 즉시 반응해야 합니다.
// ============================================================================

// Duty updates only at period boundaries; enable=0 cuts the pin immediately.
module pwm_period #(parameter integer PERIOD=5000)(
    input wire clk,input wire rst,input wire enable,input wire [12:0] duty,
    output wire pwm,output reg [12:0] active_duty);
    reg [31:0] count;reg [31:0] threshold;
    wire [12:0] limited=(duty>4096)?13'd4096:duty; // 100%(=4096)를 넘지 않게 방어적으로 자름
    // duty(0~4096 스케일) -> 실제 카운터 threshold(0~PERIOD 스케일)로 변환.
    // >>12 는 "4096으로 나누기"와 동일(4096=2^12).
    wire [63:0] scaled=(64'd1*limited*PERIOD)>>12;
    assign pwm=enable && !rst && (count<threshold); // enable이 꺼지면 파형 중간이라도 즉시 0
    always @(posedge clk)begin
        if(rst || !enable)begin count<=0;threshold<=0;active_duty<=0;end
        else if(count==PERIOD-1)begin
            // 주기 경계: 카운터를 리셋하고, "다음 주기에 쓸" threshold를 지금 확정한다.
            // active_duty는 "실제로 지금 이 파형에 반영되고 있는 duty가 몇 %인지"를
            // 밖에서 관찰할 수 있게 해주는 디버그/관측용 출력이다.
            count<=0;threshold<=scaled[31:0];active_duty<=limited;
        end
        else count<=count+1'b1;
    end
endmodule
