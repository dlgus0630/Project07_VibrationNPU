// [공부용 주석 사본] fourier/rtl/mac_pe.v
// 실제 커밋되는 원본에는 이런 상세 주석이 없습니다. 이 파일은 학습 전용입니다.
// ============================================================================
//
// 이 모듈이 하는 일 한 줄 요약: "곱하고 누적한다"(Multiply-Accumulate, MAC) —
// 신경망 계산의 가장 기본이 되는 최소 단위(Processing Element, PE)입니다.
//
// 신경망 추론이 결국 무엇을 계산하는가?
// -----------------------------------------------------------------------
// 완전연결층(fully-connected layer) 하나의 출력 하나는 결국
//   출력 = bias + (입력1 * 가중치1) + (입력2 * 가중치2) + ... + (입력N * 가중치N)
// 입니다. 이 "곱하고 더하기"를 N번 반복하는 게 전부입니다. 이 모듈은 그중
// "한 번의 곱셈 + 누적"을 담당하는 하드웨어 부품이고, 위쪽의 npu_2pe.v가
// 이 부품을 여러 번 재사용(4번, 입력 4개짜리 계층이므로)해서 전체 합을
// 만듭니다.
//
// 왜 이렇게 작은 단위로 쪼갰는가?
// -----------------------------------------------------------------------
// FPGA에는 곱셈을 전용으로 잘하는 하드웨어 블록(DSP48 등)이 한정된 개수만
// 있습니다. "모든 곱셈을 한 클럭에 동시에" 하려면 그만큼 많은 곱셈기가
// 필요한데, 이 프로젝트는 NPU 이름 자체가 "2pe"(2개의 PE)인 것에서
// 알 수 있듯, 적은 수의 곱셈기를 여러 클럭에 걸쳐 재사용하는 방식을
// 택했습니다. 대신 계산이 여러 클럭 걸리지만, 회로가 훨씬 작아집니다
// (면적 대 속도의 트레이드오프 — 임베디드 NPU 설계의 전형적인 선택).
//
// 세 가지 동작 모드: rst / clear / enable
// -----------------------------------------------------------------------
// - `rst`: 완전 초기화, acc를 0으로.
// - `clear`: "새 누적을 시작한다"는 뜻으로, acc를 0이 아니라 **bias 값으로**
//   불러옵니다. 왜 0이 아니라 bias냐면, 어차피 최종 결과에 bias를 더해야
//   하는데, 그걸 "누적의 초기값"으로 미리 넣어두면 따로 마지막에 bias를
//   더하는 단계가 필요 없어집니다 — 영리한 절약입니다.
// - `enable`: 매 클럭 `product`(이번 곱셈 결과)를 누적값에 더합니다.
//   `enable`이 꺼져 있으면 acc는 그대로 유지(hold)됩니다 — "한 클럭 쉬어도
//   된다"는 유연성을 주는 신호입니다.
// 이 세 가지 중 rst가 최우선, 그다음 clear, 그다음 enable 순서로 체크되는
// 것을 always 블록의 if-else if 순서에서 볼 수 있습니다(우선순위 인코딩).
//
// 부호 확장(sign extension)이 왜 필요한가?
// -----------------------------------------------------------------------
// `x`와 `weight`는 둘 다 signed 8비트(INT8, -128~127)입니다. 둘을 곱하면
// 최대 16비트(signed 15비트+부호1비트)가 필요합니다(`product`가 정확히
// signed [15:0]). 그런데 누적값 `acc`는 signed 32비트입니다(여러 번 더해도
// 넘치지 않도록 여유 있게 잡음). 16비트 값을 32비트 레지스터에 더하려면,
// 부호를 유지한 채로 자릿수를 늘려야 하는데, 이게 바로
// `{{16{product[15]}},product}`입니다 — "product의 맨 앞 비트(부호비트)를
// 16번 복사해서 앞에 붙인다"는 뜻으로, 음수면 1을, 양수면 0을 16개 채워서
// 32비트로 만듭니다. 이렇게 해야 음수 값도 정확하게 32비트로 확장됩니다
// (단순히 0을 채우면 음수의 크기가 완전히 틀어집니다).
// ============================================================================

// One signed INT8 MAC per enabled clock. clear has priority and loads INT32 bias.
module mac_pe(input wire clk,input wire rst,input wire clear,input wire enable,
    input wire signed [7:0] x,input wire signed [7:0] weight,
    input wire signed [31:0] bias,output reg signed [31:0] acc);
    // 조합 논리: 이번 클럭에 곱할 값을 미리 계산해둔다(레지스터에 저장하기 전).
    // 8비트 x 8비트 = 최대 16비트 필요.
    wire signed [15:0] product=x*weight;
    always @(posedge clk) begin
        if(rst) acc<=0;                          // 최우선: 완전 초기화
        else if(clear) acc<=bias;                 // 그다음: 새 누적 시작(bias로 초기화)
        else if(enable) acc<=acc+{{16{product[15]}},product}; // 매 클럭: 누적
        // 위 세 조건이 다 아니면(else 없음) acc는 이전 값을 그대로 유지(hold) —
        // Verilog에서 always 블록 안에 대입이 없으면 레지스터가 자동으로 값을 유지합니다.
    end
endmodule
