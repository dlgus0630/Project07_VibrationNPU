// 이 모듈이 하는 일 한 줄 요약: "리셋 신호를 안전하게 만들어주는 어댑터"
//
// FPGA에서 왜 "리셋"이 그냥 단순하지 않은가?
// -----------------------------------------------------------------------
// 보통 리셋 버튼을 누르면 그 신호가 클럭과 아무 상관없이 아무 때나(비동기로)
// 0에서 1로 바뀝니다. 그런데 이 신호를 그대로 수백 개의 플립플롭(레지스터)에
// "비동기 리셋"으로 직접 연결하면 두 가지 문제가 생깁니다:
//
// 1) 리셋이 "풀리는"(1→0) 그 순간이 클럭 엣지와 아주 가까우면, 어떤 플립플롭은
//    "리셋된 상태"로, 바로 옆 플립플롭은 "리셋 안 된 상태"로 어긋나게 깨어날 수
//    있습니다(메타스테이블/스큐 문제). 즉 회로 전체가 정확히 같은 순간에
//    "이제 정상 동작 시작"이라고 합의를 못 할 위험이 있습니다.
// 2) 비동기 신호가 FPGA 내부 배선을 타고 퍼지면서 도착 시간이 조금씩 다를 수
//    있어서, 이것도 스큐(도착 시간 차이)를 만듭니다.
//
// 그래서 업계 표준 해법이 "비동기 assert(리셋 걸기), 동기 release(리셋 풀기)"
// 패턴입니다. 리셋을 "거는" 것(문제가 생기면 즉시 멈춰야 하니까)은 비동기로 빨리
// 반응하게 두고, 리셋을 "푸는"것(다시 정상 동작을 시작하는 것)은 클럭에 맞춰
// 딱 떨어지게 만드는 겁니다.
//
// 이 모듈의 동작
// -----------------------------------------------------------------------
// - `async_reset`이 1이 되는 순간(클럭과 무관하게) → 즉시 내부 2비트 레지스터를
//   전부 1로 만듭니다(리셋 상태로 "거는" 것은 비동기, 즉시 반응).
// - `async_reset`이 0으로 내려가면 → 그 다음부터는 클럭이 뛸 때마다
//   `reset_pipe`에 0을 한 비트씩 밀어 넣습니다(시프트 레지스터).
//   `{reset_pipe[0], 1'b0}`이라는 표현은 "현재 0번 비트를 1번 자리로 밀고,
//   0번 자리에는 새로 0을 채운다"는 뜻 — 즉 두 클럭에 걸쳐서 서서히
//   `11 → 10 → 00`으로 풀립니다.
// - 출력 `sync_reset`은 이 2비트 레지스터의 상위 비트(`reset_pipe[1]`)만
//   봅니다. 그래서 리셋이 풀리는 시점은 "클럭 엣지 딱 맞춰서"만 바뀝니다 —
//   이게 바로 "동기적으로 release된다"는 뜻입니다.
//
// 이런 "N비트 시프트 레지스터로 신호를 몇 클럭 지연시키면서 안정화한다"는
// 패턴은 이 프로젝트 전체에서 계속 나옵니다(예: encoder_a/b를 2단
// ASYNC_REG로 동기화하는 것도 같은 발상의 변형입니다 — 다만 그건 "리셋"이
// 아니라 "비동기 입력 핀"을 다룰 때 쓰는 패턴입니다).
//
// `(* ASYNC_REG = "TRUE" *)`가 뭔가?
// -----------------------------------------------------------------------
// Xilinx Vivado에게 주는 "합성 속성(attribute)"입니다. "이 레지스터는 비동기
// 신호를 받아들이는 첫 단계이니, 배치·배선할 때 최대한 가깝게 붙여서
// 메타스테이블 전파 시간을 최소화해줘"라는 지시입니다. 이게 없으면 툴이
// 이 레지스터 쌍을 일반 로직처럼 취급해서, 물리적으로 멀리 떨어뜨려
// 배치할 수도 있고, 그러면 오히려 메타스테이블이 안정화되기 전에
// 다음 레지스터로 전파될 위험이 커집니다.
//
// `initial reset_pipe = 2'b11;`이 뭔가?
// -----------------------------------------------------------------------
// FPGA는 전원이 켜지는 순간 내부 레지스터들이 비트스트림에 저장된 초기값으로
// 세팅됩니다(이건 진짜 ASIC 칩과 다른 FPGA만의 특징입니다 — 미리 구워놓은
// 값으로 시작할 수 있음). 그래서 `initial` 블록으로 "전원 켜지자마자
// 리셋 상태(11)로 시작"을 보장해둡니다 — 이게 주석에서 말하는 "짧은
// FPGA power-on reset"입니다. 버튼을 안 눌러도 최초 전원 인가 시 자동으로
// 리셋 상태에서 출발한다는 뜻입니다.
// ============================================================================

// Asynchronous assertion, synchronous release, plus a short FPGA power-on reset.
// This is ordinary Verilog-2001; no SystemVerilog constructs are used.
module reset_sync(
    input  wire clk,
    input  wire async_reset,
    output wire sync_reset
);
    (* ASYNC_REG = "TRUE" *) reg [1:0] reset_pipe;

    initial reset_pipe = 2'b11;

    always @(posedge clk or posedge async_reset) begin
        // ↑ 이 always 블록의 민감도 리스트(sensitivity list)에 posedge async_reset이
        // 있다는 것 자체가 "비동기적으로 반응한다"는 뜻입니다. 클럭이 안 뛰어도
        // async_reset이 뛰면 즉시 이 블록이 실행됩니다.
        if (async_reset)
            reset_pipe <= 2'b11;          // 비동기로 즉시 리셋 상태로 "건다"
        else
            reset_pipe <= {reset_pipe[0],1'b0}; // 클럭마다 0을 한 비트씩 밀어 넣는다(동기적으로 "푼다")
    end

    assign sync_reset = reset_pipe[1]; // 상위 비트만 내보내므로, 리셋이 풀리는 시점은 클럭에 딱 맞음
endmodule
