function v=fourier_fft_sl(u)
% [주1] Simulink 선 하나로 실수부와 허수부를 함께 전달하는 FFT 연결 함수입니다.
% 입력 u: 원본 정수 64개. 출력 v: 128x1이며 v(1:64)=실수부, v(65:128)=허수부입니다.
% FFT 내부의 단계별 /2 때문에 결과 크기는 FFT/64에 대응합니다(정수화 오차 포함).
% 여기서는 평균 제거나 창 함수를 적용하지 않습니다. 원본 DC도 FFT에 그대로 들어갑니다.
% 세 번째 출력인 특징값은 받지 않습니다. 다음 특징 추출 블록이 같은 규칙으로 계산합니다.
[a,b]=fft64_fixed(u); v=[a;b];
end
