function dataset = load_measured_vibration(root)
% 읽는 순서: 수집 조건 확인 → 원본 파일 확인 → 64개씩 프레임 복원 → 분할 확인.
% 입력 root: Project07_VibrationNPU 폴더 경로. 생략하면 이 파일에서 찾습니다.
% 출력 dataset.runs(k).raw: [프레임 수 x 64]의 X축 센서 원시 정수값(counts).
% 출력 dt_us는 [프레임 수 x 64]의 시간 간격(마이크로초), model은 기존 학습값입니다.
% [주1] 여기서 '실측'은 저장된 센서 기록을 뜻합니다. counts를 보정된 가속도로
% 바꾸거나, 측정하지 않은 Y/Z축 신호를 만들어 내지는 않습니다.
%LOAD_MEASURED_VIBRATION Strictly import the six recorded X-axis captures.
% No signal generation, resampling, gap filling, concatenation, or axis
% reconstruction occurs here. Each row of .raw is one original 64-sample
% frame. The ADC counts, frame order, and measured within-frame intervals
% are preserved exactly. The host stamp is the frame receipt time; it is
% not a sensor sample timestamp and must not join adjacent frames.
if nargin < 1 || isempty(root)
    root = fileparts(fileparts(fileparts(mfilename('fullpath'))));
end
root = char(root);
manifestPath = fullfile(root, 'data', 'dataset_source.json');
manifest = jsondecode(fileread(manifestPath));
% manifest는 어떤 파일을 어떤 조건에서 수집했는지 적은 데이터 출처 목록입니다.
% assert는 조건이 맞지 않으면 중단하여 잘못된 파일이 분석에 섞이지 않게 합니다.
require_fields(manifest, {'type','sample_rate_hz','sensor','axis','range_g', ...
    'samples_per_window','split_by','label_map','train_run_ids', ...
    'validation_run_ids','train_windows','validation_windows','source_runs'}, ...
    'dataset_source.json');
assert(strcmp(manifest.type, 'real') && strcmp(manifest.split_by, 'run_id'), ...
    'Measured:NotRecorded', 'A real, run-separated measurement manifest is required.');
assert(manifest.sample_rate_hz == 1000 && manifest.samples_per_window == 64 && ...
    strcmp(manifest.sensor, 'MPU-6500') && strcmp(manifest.axis, 'X') && ...
    manifest.range_g == 2 && manifest.label_map.normal == 0 && ...
    manifest.label_map.abnormal == 1, 'Measured:ManifestConfiguration', ...
    'Unexpected sensor, axis, sample rate, frame length, range, or label map.');
trainIDs = cellstr(string(manifest.train_run_ids(:)));
% [주2] train/validation은 기존 학습/검증 실험 구분입니다. 같은 실험의 프레임은
% 서로 비슷할 수 있어 run_id 전체를 한쪽에만 두며, 새로운 시험 세트는 아닙니다.
valIDs = cellstr(string(manifest.validation_run_ids(:)));
allIDs = [trainIDs; valIDs];
assert(numel(unique(allIDs)) == numel(allIDs), 'Measured:SplitOverlap', ...
    'Run IDs must be unique within and between the training and validation splits.');
sources = manifest.source_runs;
assert(numel(sources) == numel(allIDs), 'Measured:RunCount', ...
    'The source list and split lists have different lengths.');
sourceIDs = string({sources.run_id});
assert(numel(unique(sourceIDs)) == numel(sourceIDs) && ...
    isequal(sort(sourceIDs(:)), sort(string(allIDs(:)))), ...
    'Measured:MissingRun', 'Every source run must appear in exactly one split.');
runs = struct([]);
for k = 1:numel(sources)
    source = sources(k);
    require_fields(source, {'run_id','condition','windows','file','sha256', ...
        'metadata_sha256','acquisition'}, 'source run');
    assert(~isempty(regexp(source.run_id, '^[A-Za-z0-9_-]+$', 'once')), ...
        'Measured:RunName', 'Invalid run ID.');
    expectedRelative = ['measurements/final_50pct/' source.run_id '.csv'];
    assert(strcmp(strrep(source.file, '\', '/'), expectedRelative), ...
        'Measured:SourcePath', 'Unexpected source path for %s.', source.run_id);
    csvPath = fullfile(root, 'measurements', 'final_50pct', [source.run_id '.csv']);
    metaPath = fullfile(root, 'measurements', 'final_50pct', [source.run_id '.json']);
    csvHash = measured_sha256(csvPath);
    % [주3] SHA-256은 파일 내용의 지문입니다. 출처 목록의 지문과 같아야
    % 원본 이후 바뀌지 않은 기록으로 취급합니다. 센서의 정확도까지 보증하지는 않습니다.
    metaHash = measured_sha256(metaPath);
    assert(strcmpi(csvHash, source.sha256), 'Measured:CSVHash', ...
        'Recorded CSV SHA-256 mismatch: %s', csvPath);
    assert(strcmpi(metaHash, source.metadata_sha256), 'Measured:MetadataHash', ...
        'Metadata SHA-256 mismatch: %s', metaPath);
    meta = jsondecode(fileread(metaPath));
    require_fields(meta, {'format_version','run_id','condition','label', ...
        'sample_rate_hz','sensor','axis','range_g','samples_per_window', ...
        'windows','supply_v','motor_duty_pct','capture_csv'}, metaPath);
    assert(isequaln(orderfields(meta), orderfields(source.acquisition)), ...
        'Measured:MetadataManifest', 'Metadata disagrees with the manifest: %s', metaPath);
    assert(strcmp(meta.run_id, source.run_id) && strcmp(meta.condition, source.condition), ...
        'Measured:RunMetadata', 'Run identity/condition mismatch: %s', metaPath);
    assert(any(strcmp(meta.condition, {'normal','abnormal'})) && ...
        meta.label == manifest.label_map.(meta.condition), ...
        'Measured:Label', 'Invalid measured condition/label: %s', metaPath);
    assert(meta.format_version == 1 && meta.sample_rate_hz == 1000 && ...
        strcmp(meta.sensor, 'MPU-6500') && strcmp(meta.axis, 'X') && ...
        meta.range_g == 2 && meta.samples_per_window == 64 && ...
        meta.supply_v == 12 && meta.motor_duty_pct == 50 && ...
        meta.windows == source.windows && meta.windows == 60 && ...
        strcmp(meta.capture_csv, [source.run_id '.csv']), ...
        'Measured:AcquisitionConfiguration', 'Unexpected acquisition setup: %s', metaPath);
    T = readtable(csvPath, 'TextType', 'string');
    expectedColumns = {'run_id','label','condition','window','sample_index', ...
        'raw_x','dt_us','host_time_s'};
    assert(isequal(T.Properties.VariableNames, expectedColumns), ...
        'Measured:CSVColumns', 'Unexpected CSV columns: %s', csvPath);
    n = source.windows;
    assert(height(T) == n * 64 && all(string(T.run_id) == string(source.run_id)) && ...
        all(string(T.condition) == string(source.condition)) && all(T.label == meta.label), ...
        'Measured:CSVIdentity', 'Wrong row count, identity, condition, or labels: %s', csvPath);
    assert(isequal(double(T.window), repelem((0:n-1).', 64)) && ...
        isequal(double(T.sample_index), repmat((0:63).', n, 1)), ...
        'Measured:SampleOrder', 'Missing, duplicated, or reordered samples/frames: %s', csvPath);
    numeric = double([T.raw_x T.dt_us T.host_time_s]);
    assert(all(isfinite(numeric(:))) && all(T.raw_x == fix(T.raw_x)) && ...
        all(T.raw_x >= -32768 & T.raw_x <= 32767) && ...
        all(T.dt_us == fix(T.dt_us)) && all(T.host_time_s > 0), ...
        'Measured:SampleRange', 'Nonfinite/out-of-range sensor counts or timestamps: %s', csvPath);
    raw = reshape(double(T.raw_x), 64, n).';
    % [주4] CSV의 연속된 64행을 한 프레임으로 묶습니다. 행은 프레임, 열은 샘플입니다.
    % 여러 프레임 사이의 센서 시각은 없으므로 한 개의 긴 연속 파형으로 잇지 않습니다.
    dt = reshape(double(T.dt_us), 64, n).';
    stamps = reshape(double(T.host_time_s), 64, n).';
    intervals = dt(:, 2:end);
    % [주5] 각 프레임의 첫 dt=0은 시작점 표시입니다. 실제 간격 통계는 나머지 63개입니다.
    % dt_us는 프레임 내부의 센서 간격, host_time_s는 PC가 프레임을 받은 시각입니다.
    % 수신 시각의 차이에는 통신 지연 등이 섞이므로 센서 샘플 간격으로 쓰지 않습니다.
    assert(all(dt(:,1) == 0) && all(intervals(:) >= 700 & intervals(:) <= 1300), ...
        'Measured:Intervals', 'Invalid recorded within-frame intervals: %s', csvPath);
    assert(all(all(stamps == stamps(:,1))) && all(diff(stamps(:,1)) > 0), ...
        'Measured:HostTime', 'Frame receipt stamps must be constant per frame and increasing.');
    if any(strcmp(source.run_id, trainIDs))
        split = 'train';
    else
        split = 'validation';
    end
    % 시간 간격을 열 방향으로 누적하고 10^6으로 나누면 프레임 시작 기준 초(s)가 됩니다.
    run = struct('run_id', source.run_id, 'label', double(meta.label), ...
        'condition', source.condition, 'split', split, 'raw', raw, ...
        'dt_us', dt, 'relative_sample_time_s', cumsum(dt, 2) / 1e6, ...
        'host_time_s', stamps(:,1), 'window_id', (0:n-1).', ...
        'metadata', meta, 'csv_path', csvPath, 'source_sha256', csvHash, ...
        'metadata_sha256', metaHash);
    % MATLAB releases differ in whether a no-field struct([]) accepts a
    % whole struct by indexed assignment.  Seed the array with the first
    % fully formed run so every later element has the same schema.
    if k == 1
        runs = run;
    else
        runs(k) = run; %#ok<AGROW>
    end
end
verify_split(root, runs, trainIDs, 'train', manifest.train_windows);
verify_split(root, runs, valIDs, 'val', manifest.validation_windows);
modelPath = fullfile(root, 'data', 'model.json');
model = jsondecode(fileread(modelPath));
% 기존 4입력 → 4은닉 → 2출력 분류기의 정수 가중치를 읽습니다. 재학습은 하지 않습니다.
require_fields(model, {'w1','b1','w2','b2','shift1','shift2'}, modelPath);
assert(isequal(size(model.w1), [4 4]) && numel(model.b1) == 4 && ...
    isequal(size(model.w2), [2 4]) && numel(model.b2) == 2, ...
    'Measured:ModelShape', 'Expected the current 4-4-2 classifier.');
weights = double([model.w1(:); model.w2(:)]);
biases = double([model.b1(:); model.b2(:)]);
shifts = double([model.shift1; model.shift2]);
assert(all(isfinite([weights; biases; shifts])) && ...
    all(weights == fix(weights) & weights >= -128 & weights <= 127) && ...
    all(biases == fix(biases) & abs(biases) < 2^31) && ...
    all(shifts == fix(shifts) & shifts >= 0 & shifts <= 31), ...
    'Measured:ModelInteger', 'Invalid integer classifier weights/biases/shifts.');
dataset = struct('root', root, 'manifest', manifest, 'runs', runs, 'model', model, ...
    'manifest_sha256', measured_sha256(manifestPath), ...
    'model_sha256', measured_sha256(modelPath), ...
    'provenance_checked', true, 'units', 'raw sensor counts', ...
    'time_note', ['Each frame has its own relative sensor time from dt_us. ' ...
    'host_time_s is frame receipt time; inter-frame sample timing is unavailable.']);
end

function require_fields(value, names, context)
% 보조 함수: 구조체 value에 names의 필드가 있는지 확인하며, 누락 시 context를 표시합니다.
assert(isstruct(value) && all(isfield(value, names)), 'Measured:MissingFields', ...
    'Required fields are missing from %s.', context);
end

function verify_split(root, runs, ids, filePrefix, expectedWindows)
% 보조 함수: 원본 프레임과 기존 학습/검증 CSV의 값 및 순서를 비교합니다. 반환값은 없습니다.
% 입력 ids는 실험 순서이며, samples는 [전체 프레임 수 x 64], labels는 [프레임 수 x 1]입니다.
% The existing train/validation CSVs must equal the source frames byte-for-
% value in their original split order. No reshuffling or retraining occurs.
samples = zeros(0,64);
labels = zeros(0,1);
runIDs = {runs.run_id};
for k = 1:numel(ids)
    index = find(strcmp(runIDs, ids{k}));
    samples = [samples; runs(index).raw]; %#ok<AGROW>
    labels = [labels; repmat(runs(index).label, size(runs(index).raw,1), 1)]; %#ok<AGROW>
end
actualSamples = readmatrix(fullfile(root, 'data', [filePrefix '_samples.csv']));
actualLabels = readmatrix(fullfile(root, 'data', [filePrefix '_labels.csv']));
assert(size(samples,1) == expectedWindows && isequal(actualSamples, samples) && ...
    isequal(actualLabels(:), labels), 'Measured:SplitMismatch', ...
    'Existing %s samples/labels do not match the recorded source frames.', filePrefix);
end
