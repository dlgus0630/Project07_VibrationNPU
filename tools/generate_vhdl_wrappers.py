#!/usr/bin/env python3
"""Generate VHDL-93 module-reference shells for the VHDL-2008 designs.

Vivado 2024.2 IP Integrator rejects a VHDL-2008 top file as a module reference.
The shell copies the exact entity interface and attributes and wires each port
to the 2008 implementation. It contains no state or algorithmic logic.
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1] / 'fourier/vhdl'
ENTITIES = [('axi_vibration_impl', 'axi_vibration_top', 'axi_vibration_struct.vhd'),
            ('fourier_motor_impl', 'fourier_motor_control', 'fourier_motor_struct.vhd')]


def parenthesized(text, keyword):
    match = re.search(r'\b' + keyword + r'\s*\(', text, re.I)
    if not match:
        raise ValueError(f'Missing {keyword} clause')
    start = text.index('(', match.start())
    depth = 0
    for index in range(start, len(text)):
        if text[index] == '(':
            depth += 1
        elif text[index] == ')':
            depth -= 1
            if depth == 0:
                return text[start + 1:index]
    raise ValueError(f'Unclosed {keyword} clause')


def names(text):
    result = []
    for declaration in text.split(';'):
        before, _, _ = declaration.partition(':')
        result.extend(re.findall(r'\b[A-Za-z][A-Za-z0-9_]*\b', before))
    if len(result) != len(set(name.lower() for name in result)):
        raise ValueError('Duplicate interface name')
    return result


def main():
    for implementation, wrapper, filename in ENTITIES:
        src = (ROOT / filename).read_text(encoding='utf-8')
        entity = re.search(r'\bentity\s+' + implementation + r'\s+is\b.*?\bend\s+entity(?:\s+\w+)?\s*;',
                           src, re.I | re.S)
        if not entity:
            raise ValueError(f'Entity not found: {implementation}')
        body = entity.group(0)
        interface = re.sub(r'(\bentity\s+)' + implementation + r'(\s+is\b)',
                           r'\g<1>' + wrapper + r'\g<2>', body, count=1, flags=re.I)
        interface = re.sub(r'(\bend\s+entity\s+)' + implementation + r'\b',
                           r'\g<1>' + wrapper, interface, flags=re.I)
        generics = names(parenthesized(body, 'generic'))
        ports = names(parenthesized(body, 'port'))
        mappings = lambda items: ',\n        '.join(f'{name} => {name}' for name in items)
        declarations = ''
        # Vivado's module-reference parser expects port interface attributes
        # in the architecture declarative region (UG994, General Usage).
        attribute_match = re.search(r'\n\s*attribute\b', interface, re.I)
        if attribute_match:
            attribute_end = re.search(r'\bend\s+entity(?:\s+\w+)?\s*;', interface, re.I)
            declarations = interface[attribute_match.start():attribute_end.start()].lstrip('\n')
            interface = interface[:attribute_match.start()] + '\nend entity;'
        generic_mapping = mappings(generics)
        if implementation == 'fourier_motor_impl':
            # VHDL-93 forbids one generic default from referring to another
            # generic in the same list. Resolve this default at elaboration;
            # explicit nonnegative WATCHDOG_CYCLES values pass through exactly.
            interface, count = re.subn(
                r'(WATCHDOG_CYCLES\s*:\s*integer\s*:=)\s*CLK_HZ\s*/\s*2',
                r'\g<1>-1', interface, flags=re.I)
            if count != 1:
                raise ValueError('Expected the CLK_HZ/2 watchdog default')
            declarations += (
                '    -- -1 selects the original CLK_HZ/2 default at elaboration.\n'
                '    function watchdog_default(value, frequency : integer) return integer is\n'
                '    begin\n'
                '        if value = -1 then return frequency/2; else return value; end if;\n'
                '    end;\n')
            generic_mapping = re.sub(
                r'WATCHDOG_CYCLES\s*=>\s*WATCHDOG_CYCLES',
                'WATCHDOG_CYCLES => watchdog_default(WATCHDOG_CYCLES, CLK_HZ)',
                generic_mapping, flags=re.I)
        content = ('-- Auto-generated by tools/generate_vhdl_wrappers.py; no logic or state.\n'
                   'library ieee;\nuse ieee.std_logic_1164.all;\n\n' + interface + '\n'
                   f'architecture rtl of {wrapper} is\n' + declarations + 'begin\n'
                   f'    U_IMPL: entity work.{implementation}(structural)\n'
                   f'    generic map (\n        {generic_mapping})\n'
                   f'    port map (\n        {mappings(ports)});\n'
                   'end architecture;\n')
        (ROOT / (wrapper + '.vhd')).write_text(content, encoding='utf-8')
        print(f'{wrapper}: {len(generics)} generics, {len(ports)} ports')


if __name__ == '__main__':
    main()
