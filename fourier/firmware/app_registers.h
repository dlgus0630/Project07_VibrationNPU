#ifndef APP_REGISTERS_H
#define APP_REGISTERS_H

/* ARM이 접근하는 AXI/BRAM 주소. vibration_regs.vhd와 같은 계약이다. */
#define CONTROL_BASE_ADDRESS 0x43c00000U
#define SAMPLE_RAM_BASE_ADDRESS 0x40000000U

enum {
    REG_CONTROL = 0x000,
    REG_STATUS = 0x004,
    REG_TOTAL_CYCLES = 0x00c,
    REG_NPU_CYCLES = 0x010,
    REG_SPI_COMMAND = 0x040,
    REG_SPI_STATUS = 0x044,
    REG_HEARTBEAT = 0x048,
    REG_SAFETY_DETAIL = 0x04c,
    REG_SPEED_REFERENCE = 0x050,
    REG_SPEED_MEASURED = 0x054,
    REG_MOTOR_DUTY = 0x058,
    REG_PID_INTEGRAL = 0x05c,
    REG_MOTOR_ARMED = 0x060,
    REG_CONTROL_2 = 0x068,
    REG_OPEN_LOOP_DUTY = 0x06c,
    REG_KP_GAIN = 0x070,
    REG_KI_GAIN = 0x074,
    REG_QUAD_POSITION = 0x07c
};

enum {
    STATUS_BUSY = 1U << 0,
    STATUS_DONE = 1U << 1,
    STATUS_ERROR = 1U << 2,
    STATUS_LATCHED = 1U << 3,
    STATUS_WARNING = 1U << 4,
    STATUS_DERATED = 1U << 5,
    STATUS_WATCHDOG = 1U << 6,
    CONTROL_2_OPEN_LOOP = 1U << 0,
    CONTROL_2_ANTI_WINDUP = 1U << 1
};

#define HEARTBEAT_INTERVAL_US 100000U
#define TELEMETRY_INTERVAL_US 10000U
#define DUTY_VALUE_MASK 0x1fffU

#endif
